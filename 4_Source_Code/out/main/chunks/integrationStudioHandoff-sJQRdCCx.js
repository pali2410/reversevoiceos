function buildStudioAgentsMd(manifest) {
  return `# Working on this VoiceOS integration (guide for AI coding agents)

You are editing **${manifest.name}**, a VoiceOS integration generated by the
VoiceOS Integration Studio: a folder that teaches the VoiceOS voice agent new
tools, with native UI in the Mac notch. This file is the whole contract — no
VoiceOS internals needed.

## What a user experiences

The user talks to VoiceOS. The agent picks one of the tools declared here,
VoiceOS runs this folder's MCP server (\`server.ts\`), and the result appears
two ways: the model narrates the data, and the notch shows the tool's
**glance card** (the \`_voiceos_glance\` blocks the tool attaches to its
result). Tools that act on the user's behalf first show a **confirmation
card** declared in the manifest, which the user can edit and approve.

## Files

- \`voiceos.integration.json\` — identity, runtime, permissions, tools
  (name/description/inputSchema/confirmation). Every manifest tool must be
  registered in server.ts with the same name, and vice versa. Keep
  \`runtime\` exactly as generated — VoiceOS resolves it to the launcher for
  the user's OS.
- \`server.ts\` — standard MCP stdio server (@modelcontextprotocol/sdk + zod).
- \`run.sh\` / \`run.cmd\` — the launchers VoiceOS invokes (macOS / Windows);
  leave them alone.
- \`package.json\` — add dependencies here, then \`bun install\`.
- \`icon.png\` / \`studio-meta.json\` — the Studio's icon and preview fixtures;
  safe to leave untouched.

## Rules that make integrations feel native

1. **Tool descriptions are routing rules for the model**: what it does + when
   to use it ("Use when the user asks …").
2. **Results carry data AND a glance card**: JSON the model reasons about,
   plus a \`_voiceos_glance: { blocks: [...] }\` key spread into the result
   for the user. Never put information only in the card.
3. **Glance cards are a 2-second read** — max 3 blocks. Vocabulary:
   \`header\` {icon?, title, trailing?}, \`list\` {header?, rows: [{icon?,
   title, subtitle?, trailing?, badge?: {text, tone?}}]} (≤6 rows), \`stats\`
   {items: [{label, value, delta?, tone?}]} (≤3), \`keyValue\` {pairs:
   [[label, value]]} (≤5), \`bars\` {labels, values, unit?} / \`line\`
   {points, tone?, baseline?} / \`splitBar\` {segments} (max ONE chart),
   \`progress\` {value, max?, label?, style?: "bar"|"ring"}, \`badges\`
   {items} (≤3), \`clock\` {tz}, \`countdown\` {until|seconds}, \`divider\`,
   \`row\` {children} (2-3 side by side). tone is "neutral"|"good"|"bad".
   Titles ≤60 chars; pre-trim strings. Off-schema blocks are silently
   dropped.
4. **Anything that acts needs a manifest \`confirmation\` card.** Inputs bind
   to args with \`{{argName}}\`; edited values are what execute. Interactive
   vocabulary: card, stack, text, markdown, keyValue, metadata, list/listItem,
   image, badge, divider, progress, textField, passwordField, select, toggle,
   chips (inputs take \`bind\`), actions (roles confirm/cancel/copy/openUrl —
   exactly one confirm and one cancel, in a footer actions block). Read-only
   tools must NOT declare one.
5. **Be honest**: throw on failure; never fabricate data or claim success.
   Use \`console.error\` for debug logging (stdout is the MCP wire).
6. **Least privilege**: the manifest's network permission lists only domains
   the code actually calls.
7. **Long work (>20s) declares** \`"execution": {"mode": "background"}\` +
   the \`background\` permission.
8. **Secrets come from the user**: declare manifest \`preferences\` (type
   "password" for secrets); VoiceOS injects them as env vars named after each
   field (\`process.env.MY_FIELD\`). Never hardcode keys.

## Dev loop

\`\`\`bash
bun install        # once, and after adding dependencies
bun server.ts      # starts the MCP server; Ctrl-C when it idles cleanly
\`\`\`

Then in VoiceOS: Dashboard → Agent tab → Integration Studio → My
Integrations → open **${manifest.name}** → **Reload**. The agent sees your
changes on its next turn — just talk to it.

## Definition of done

- Manifest tools and server.ts registrations match exactly.
- Each tool description says when the model should call it.
- Acting tools have confirmation cards; read tools don't.
- Glance cards read in 2 seconds.
`;
}
function writeStudioHandoffFiles(serverDir, manifest) {
  try {
    fs.writeFileSync(
      path.join(serverDir, "AGENTS.md"),
      buildStudioAgentsMd(manifest),
      "utf-8"
    );
  } catch (err) {
    console.warn(
      "[IntegrationStudio] AGENTS.md write failed:",
      err instanceof Error ? err.message : err
    );
  }
}
const MACOS_APP_NAMES = {
  cursor: "Cursor"
};
const CLI_BINARIES = {
  cursor: "cursor"
};
async function openHandoffDir(target, dir) {
  if (target === "finder") {
    if (!fs.existsSync(dir)) {
      return { success: false, error: "That folder is no longer on disk." };
    }
    const error = await electron.shell.openPath(dir);
    if (!error) return { success: true };
    try {
      electron.shell.showItemInFolder(dir);
      return { success: true };
    } catch {
      return { success: false, error };
    }
  }
  const appName = MACOS_APP_NAMES[target];
  return new Promise((resolve) => {
    const finish = (err) => resolve(
      err ? {
        success: false,
        error: `${appName} doesn't seem to be installed.`
      } : { success: true }
    );
    if (process.platform === "darwin") {
      node_child_process.execFile("open", ["-a", appName, dir], finish);
    } else {
      node_child_process.execFile(CLI_BINARIES[target], [dir], { shell: true }, finish);
    }
  });
}
function shellQuote(value) {
  return `'${value.replace(/'/g, `'\\''`)}'`;
}
function psQuote(value) {
  return `'${value.replace(/'/g, "''")}'`;
}
function buildHandoffCommand(tool, dir, integrationName) {
  const safeName = integrationName.replace(/"/g, "”");
  const prompt = `Read AGENTS.md first — it explains the VoiceOS integration contract. Then help me improve the “${safeName}” integration in this folder.`;
  if (process.platform === "win32") {
    return `cd ${psQuote(dir)}; ${tool} ${psQuote(prompt)}`;
  }
  return `cd ${shellQuote(dir)} && ${tool} ${shellQuote(prompt)}`;
}
exports.buildHandoffCommand = buildHandoffCommand;
exports.buildStudioAgentsMd = buildStudioAgentsMd;
exports.openHandoffDir = openHandoffDir;
exports.writeStudioHandoffFiles = writeStudioHandoffFiles;
